/**
 * Язык страницы в jsdom-тестах.
 *
 * Сайт подстраивает язык под гостя: сначала ссылка ?lang=, потом прошлый выбор
 * (cookie/localStorage), потом язык браузера, потом страна по заголовку CDN.
 * jsdom не умеет отправлять Accept-Language от лица посетителя — он всегда
 * шлёт «en», — поэтому тесты, которые проверяют русские подписи, просят
 * русскую версию явно, тем же способом, что и кнопка-переключатель языка.
 *
 * Проверка самой авто-подстройки живёт рядом: `tests/lang_auto.js` (клиент) и
 * `tests/test_site_i18n.py` (сервер).
 *
 *     const { ru } = require("./_ru");
 *     await JSDOM.fromURL(ru(URL_BASE + "/terminal"), { ... });
 */

"use strict";

/** Тот же адрес, но с явно выбранным русским языком. */
function ru(url) {
  return url + (url.indexOf("?") === -1 ? "?" : "&") + "lang=ru";
}

module.exports = { ru };
